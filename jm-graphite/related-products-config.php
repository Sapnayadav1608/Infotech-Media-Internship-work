    global $productPagesConfig;
    $productNames = isset($productPagesConfig[$page]) ? $productPagesConfig[$page] : [];
    $products = [];
    
    foreach ($productNames as $name) {
        $products[] = [
            'name' => $name,
            'image' => getProductImage($name),
            'link' => getProductLink($name)
        ];
    }
    
    return $products;
}

